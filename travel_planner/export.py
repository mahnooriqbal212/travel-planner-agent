"""Turn a result into a downloadable markdown document (shared by CLI and UI)."""

import re

from .models import TripPlanResult


def to_markdown(result: TripPlanResult) -> str:
    req = result.request
    header = (
        f"<!-- Generated by Travel Planner Agent -->\n"
        f"> **{req.destination}** · {req.start_date:%d %b %Y} – {req.end_date:%d %b %Y} "
        f"· {req.num_days} days · {req.travelers} traveler(s) · "
        f"budget {req.budget:,.0f} {req.currency}\n\n"
    )
    footer = "\n\n---\n*AI-generated plan: verify prices, opening hours and entry rules before you travel.*\n"
    return header + result.final_plan + footer


def safe_filename(result: TripPlanResult) -> str:
    """A filesystem-safe name like 'trip-paris-2026-12-01.md'."""
    slug = re.sub(r"[^a-z0-9]+", "-", result.request.destination.lower()).strip("-") or "trip"
    return f"trip-{slug[:40]}-{result.request.start_date:%Y-%m-%d}.md"
